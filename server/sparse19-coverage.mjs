import {keyOf} from './sparse19-nsga.mjs';
import {rawRange} from './sparse19-range.mjs';
import {RANGE19_PROTOCOL} from '../src/smart19Config.js';
export const COVERAGE_PROTOCOL=RANGE19_PROTOCOL;
const order=direction=>(a,b)=>(direction==='LOW'?a.prediction-b.prediction:b.prediction-a.prediction)||a.key.localeCompare(b.key);
export async function coverageRange(raw,bank,config=COVERAGE_PROTOCOL){
 const start=performance.now(),probes=[];
 for(let j=0;j<19;j++)for(const p of [-2,2]){const x=Array(19).fill(0);x[j]=p;if(raw.validateTuple(x))probes.push(x);}
 await raw.evaluateTuples(probes);
 const lo=Array(19).fill(0),hi=Array(19).fill(0);
 for(let j=0;j<19;j++){
  const n=Array(19).fill(0),p=Array(19).fill(0);n[j]=-2;p[j]=2;
  const a=raw.cache.get(keyOf(n)),b=raw.cache.get(keyOf(p));
  if(a&&b&&a.prediction!==b.prediction){lo[j]=a.prediction<b.prediction?-15:15;hi[j]=-lo[j];}
 }
 const candidates=[...bank.slice(0,config.bankBudget),lo,hi,Array(19).fill(-15),Array(19).fill(15)];
 await raw.evaluateTuples(candidates.filter(x=>raw.validateTuple(x)));
 const initialRange=rawRange(raw.rows(),raw.p0),jobs=[];
 for(const direction of ['LOW','HIGH']){
  const ranked=raw.rows().sort(order(direction)),selected=[];
  // Use separate basins: best observed point, then the READY baseline.
  for(const point of [ranked[0],raw.cache.get(keyOf(Array(19).fill(0))),...ranked]){
   if(selected.length>=config.starts)break;
   if(!selected.some(r=>r.key===point.key))selected.push(point);
  }
  selected.forEach(point=>jobs.push({direction,point,rounds:[],stationary:false,pairPasses:0,pairCertified:false}));
 }
 for(let round=1;round<=config.maxRounds&&jobs.some(j=>!j.stationary);round++){
  const all=[],pending=[];
  for(const job of jobs.filter(j=>!j.stationary)){
   const tuples=[];
   for(let j=0;j<19;j++)for(let p=-15;p<=15;p++){
    if(p===job.point.x[j])continue;const x=job.point.x.slice();x[j]=p;
    if(raw.validateTuple(x)){tuples.push(x);all.push(x);}
   }
   pending.push({job,tuples});
  }
  await raw.evaluateTuples(all);
  for(const {job,tuples} of pending){
   const before=job.point,best=[before,...tuples.map(x=>raw.cache.get(keyOf(x)))].sort(order(job.direction))[0];
   const improvement=job.direction==='LOW'?before.prediction-best.prediction:best.prediction-before.prediction;
   job.stationary=improvement<=0;job.point=improvement>0?best:before;
   job.rounds.push({round,before:before.prediction,after:job.point.prediction,improvement,evaluatedNeighbors:tuples.length});
  }
  // Both endpoints belong to the full evaluated archive, including trials
  // generated by the other direction. Wake an endpoint if that archive grew.
  for(const job of jobs){const outer=raw.rows().sort(order(job.direction))[0];
   if((job.direction==='LOW'?outer.prediction<job.point.prediction:outer.prediction>job.point.prediction)){
    job.point=outer;job.stationary=false;
   }
  }
  // A one-coordinate stationary point can miss an improving joint move.
  // Check every two-coordinate endpoint/zero combination before publishing.
  const pairs=[];
  for(const job of jobs.filter(j=>j.stationary&&!j.pairCertified&&j.pairPasses<config.pairPasses)){
   const tuples=[];job.pairPasses++;
   for(let a=0;a<19;a++)for(let b=a+1;b<19;b++)for(const pa of [-15,0,15])for(const pb of [-15,0,15]){
    if(pa===job.point.x[a]||pb===job.point.x[b])continue;
    const x=job.point.x.slice();x[a]=pa;x[b]=pb;
    if(raw.validateTuple(x))tuples.push(x);
   }
   pairs.push({job,tuples});
  }
  if(pairs.length){await raw.evaluateTuples(pairs.flatMap(p=>p.tuples));
   for(const {job,tuples} of pairs){const before=job.point,best=[before,...tuples.map(x=>raw.cache.get(keyOf(x)))].sort(order(job.direction))[0];
    const improvement=job.direction==='LOW'?before.prediction-best.prediction:best.prediction-before.prediction;
    if(improvement>0){job.point=best;job.stationary=false;}
    else job.pairCertified=true;
    job.rounds.push({round,kind:'JOINT_PAIR_ESCAPE',before:before.prediction,after:job.point.prediction,improvement,evaluatedNeighbors:tuples.length});
   }
   for(const job of jobs){const outer=raw.rows().sort(order(job.direction))[0];
    if((job.direction==='LOW'?outer.prediction<job.point.prediction:outer.prediction>job.point.prediction)){
     job.point=outer;job.stationary=false;job.pairCertified=false;
    }
   }
  }
 }
 const range=rawRange(raw.rows(),raw.p0);
 return {range,initialRange,elapsedMs:performance.now()-start,protocol:config,stationary:jobs.every(j=>j.stationary&&j.pairCertified),
  jobs:jobs.map(j=>({...j,point:{key:j.point.key,prediction:j.point.prediction,x:j.point.x}})),...raw.snapshot()};
}
